"""GitHub Draft PR & Idempotent Reconciler Integration (Spec v2.0 Section 1.3 & 3.5)."""

from __future__ import annotations

import subprocess
from pathlib import Path
from typing import Any

import httpx

from digital_employee.models.state import DurableTaskState
from digital_employee.security.dlp import PolicyViolationError, validate_branch_target


def render_evidence_pr_body(state: DurableTaskState) -> str:
    """Format an evidence-first GitHub Draft PR description."""
    c = state.contract
    ev = state.verification_evidence
    lines = [
        f"## 🎯 Task Contract (`{state.task_id}`)",
        f"- **Objective**: {c.objective}",
        f"- **Base Branch / Commit**: `{c.base_branch}` @ `{c.base_commit_sha[:10]}`",
        f"- **Head Commit**: `{(state.head_commit_sha or '')[:10]}`",
        f"- **Permitted Scopes**: `{', '.join(c.permitted_scopes)}`",
        "",
        "## 🧪 Evidence-Based Verification Checklist",
    ]
    if ev:
        lines.extend(
            [
                "| Check | Result | Detail |",
                "| :--- | :--- | :--- |",
                f"| **Regression Fail on Baseline** | {'✅ PASS' if ev.repro_test_failed_on_base else '❌ FAIL'} | `{ev.repro_test_target}` failed on `{c.base_commit_sha[:8]}` |",
                f"| **Regression Pass on Head** | {'✅ PASS' if ev.repro_test_passed_on_head else '❌ FAIL'} | `{ev.repro_test_target}` passed on `{ev.verified_commit_sha[:8]}` |",
                f"| **Related Test Suite** | {'✅ PASS' if ev.existing_test_suite_passed else '❌ FAIL'} | Existing module & smoke tests green |",
                f"| **Anti-Tampering Check** | {'✅ PASS' if ev.tests_weakened_check else '❌ FAIL'} | No deleted asserts or added `@skip`/`xfail` |",
                f"| **Static Linter & Scope** | {'✅ PASS' if (ev.static_analysis_passed and ev.scope_compliance_check) else '❌ FAIL'} | Strict scope & lint compliance |",
                "",
            ]
        )
        if ev.reviewer_report:
            lines.append("## 🔍 Focused Single Reviewer Assessment")
            if ev.reviewer_report.summary:
                lines.append(f"> {ev.reviewer_report.summary}\n")
            for item in ev.reviewer_report.ac_assessment:
                lines.append(f"- {item}")
            lines.append("")
            lines.append("## ⚠️ Unverified Risks & Sandbox Blind Spots (Explicit Disclosure)")
            for risk in ev.reviewer_report.unverified_risks:
                lines.append(f"- {risk}")
    lines.extend(
        [
            "",
            "---",
            "*Generated by AI Digital Employee v2.0 (Draft PR only — human review & OAuth merge required).*",
        ]
    )
    return "\n".join(lines)


class GitHubIntegration:
    """Safe GitHub connector enforcing `ai-agent/*` branches and Draft-only PRs."""

    def __init__(self, token: str, api_base: str = "https://api.github.com") -> None:
        self.token = token
        self.api_base = api_base.rstrip("/")

    @property
    def is_configured(self) -> bool:
        return bool(self.token.strip())

    def _headers(self) -> dict[str, str]:
        return {
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        }

    def push_agent_branch(
        self,
        *,
        worktree_path: Path,
        branch_name: str,
        protected_branches: list[str],
    ) -> str:
        """Push `ai-agent/{task_id}` to `origin`; physically blocks protected branches."""
        validate_branch_target(branch_name, protected_branches)
        refspec = f"refs/heads/{branch_name}:refs/heads/{branch_name}"
        proc = subprocess.run(
            ["git", "push", "--force-with-lease", "origin", refspec],
            cwd=str(worktree_path),
            capture_output=True,
            text=True,
            timeout=60,
        )
        if proc.returncode != 0:
            raise RuntimeError(f"git push failed: {proc.stderr.strip()}")
        return branch_name

    def reconcile_or_create_draft_pr(
        self,
        *,
        github_repo: str,
        state: DurableTaskState,
        protected_branches: list[str],
    ) -> dict[str, Any]:
        """Reconcile existing Open PR for `ai-agent/{task_id}` or create a new Draft PR."""
        validate_branch_target(state.branch_name, protected_branches)
        if not self.is_configured:
            raise PolicyViolationError("DE_GITHUB_TOKEN is not configured; skipping remote PR creation.")

        owner, repo = github_repo.split("/", 1)
        with httpx.Client(timeout=30.0, headers=self._headers()) as client:
            # 1. Reconcile check: see if PR was already created before a crash
            list_resp = client.get(
                f"{self.api_base}/repos/{owner}/{repo}/pulls",
                params={"head": f"{owner}:{state.branch_name}", "state": "open"},
            )
            list_resp.raise_for_status()
            existing = list_resp.json()
            if existing:
                pr = existing[0]
                return {
                    "html_url": pr["html_url"],
                    "number": pr["number"],
                    "reconciled": True,
                }

            # 2. Create strictly as Draft PR (`draft=True` hardcoded; no merge API exists on this client)
            payload = {
                "title": f"[AI-Agent] {state.contract.objective[:100]}",
                "head": state.branch_name,
                "base": state.contract.base_branch,
                "body": render_evidence_pr_body(state),
                "draft": True,
            }
            create_resp = client.post(
                f"{self.api_base}/repos/{owner}/{repo}/pulls",
                json=payload,
            )
            create_resp.raise_for_status()
            pr = create_resp.json()
            return {
                "html_url": pr["html_url"],
                "number": pr["number"],
                "reconciled": False,
            }

    def post_pr_comment(
        self,
        *,
        github_repo: str,
        pr_number: int,
        body: str,
    ) -> str:
        if not self.is_configured:
            return "skipped:no_token"
        owner, repo = github_repo.split("/", 1)
        tagged_body = f"<!-- ai-digital-employee-bot -->\n🤖 **[AI Digital Employee]**\n\n{body}"
        with httpx.Client(timeout=20.0, headers=self._headers()) as client:
            resp = client.post(
                f"{self.api_base}/repos/{owner}/{repo}/issues/{pr_number}/comments",
                json={"body": tagged_body},
            )
            resp.raise_for_status()
            return str(resp.json().get("html_url", "posted"))

    def fetch_pr_state(self, *, github_repo: str, pr_number: int) -> dict[str, Any]:
        owner, repo = github_repo.split("/", 1)
        with httpx.Client(timeout=20.0, headers=self._headers()) as client:
            resp = client.get(f"{self.api_base}/repos/{owner}/{repo}/pulls/{pr_number}")
            resp.raise_for_status()
            return resp.json()

    def fetch_human_pr_comments(self, *, github_repo: str, pr_number: int) -> list[dict[str, Any]]:
        """Fetch issue & inline review comments on a PR, excluding Digital Employee's own bot replies."""
        if not self.is_configured:
            return []
        owner, repo = github_repo.split("/", 1)
        comments: list[dict[str, Any]] = []
        with httpx.Client(timeout=20.0, headers=self._headers()) as client:
            for endpoint, kind in (
                (f"{self.api_base}/repos/{owner}/{repo}/issues/{pr_number}/comments", "issue_comment"),
                (f"{self.api_base}/repos/{owner}/{repo}/pulls/{pr_number}/comments", "review_comment"),
            ):
                resp = client.get(endpoint, params={"per_page": 50})
                if resp.status_code >= 400:
                    continue
                for item in resp.json():
                    body = str(item.get("body") or "")
                    if "<!-- ai-digital-employee-bot -->" in body:
                        continue
                    path_hint = item.get("path")
                    formatted = f"[File `{path_hint}`] {body}" if path_hint else body
                    comments.append(
                        {
                            "id": f"{kind}_{item['id']}",
                            "body": formatted.strip(),
                            "created_at": str(item.get("created_at") or ""),
                            "user": str((item.get("user") or {}).get("login") or ""),
                        }
                    )
        comments.sort(key=lambda c: c["created_at"])
        return comments

    def fetch_failed_blocking_checks(self, *, github_repo: str, commit_sha: str) -> list[str]:
        """Return names of completed check-runs with conclusion=='failure' on `commit_sha`."""
        if not self.is_configured or not commit_sha:
            return []
        owner, repo = github_repo.split("/", 1)
        with httpx.Client(timeout=20.0, headers=self._headers()) as client:
            resp = client.get(
                f"{self.api_base}/repos/{owner}/{repo}/commits/{commit_sha}/check-runs"
            )
            if resp.status_code >= 400:
                return []
            runs = resp.json().get("check_runs") or []
            if not runs or any(r.get("status") != "completed" for r in runs):
                return []
            return [
                str(r.get("name"))
                for r in runs
                if r.get("conclusion") in ("failure", "timed_out")
            ]
